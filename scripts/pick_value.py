def value_for_pick(pick: int | None) -> float:
    """Return Jimmy Johnson chart value for a pick number.
    Anything past 224 (or None) returns 0.0 — treated as undrafted-equivalent."""
    if pick is None or pick < 1:
        return 0.0
    if pick > 224:
        return 0.0
    return JIMMY_JOHNSON[pick]
